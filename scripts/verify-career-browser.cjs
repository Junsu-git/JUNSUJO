const {serve,chromium,root}=require('./verify-portfolio.cjs');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
(async()=>{
 const server=await serve();
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const errors=[],failures=[];
 const output=process.env.PORTFOLIO_QA_OUTPUT;
 try{
  const context=await browser.newContext({viewport:{width:1440,height:1050},reducedMotion:'reduce'});
  await context.route(/https?:\/\/(?!127\.0\.0\.1)/,route=>route.abort());
  const page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  const origin='http://127.0.0.1:'+server.address().port;
  await page.goto(origin+'/index.html');
  await page.evaluate(()=>window.portfolioTheme.setTheme('dark'));
  await page.locator('.site-mode-switch a[href="career.html"]').click();
  await page.waitForSelector('.log-row');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark','theme survives page mode change');
  assert.equal(await page.locator('.log-row').count(),22);
  assert.equal(await page.locator('.kpi-value').first().innerText(),'22건');
  await page.locator('[data-chart-month="2026-09"]').click();
  assert.equal(await page.locator('.log-row').count(),8);
  await page.locator('[data-category="competition"]').click();
  assert.equal(await page.locator('.log-row').count(),3,'category intersects month');
  assert(page.url().includes('month=2026-09')&&page.url().includes('category=competition'));
  await page.locator('#activity-search').fill('없음없는활동');
  assert(await page.locator('#archive-empty').isVisible());
  await page.locator('#empty-reset').click();
  assert.equal(await page.locator('.log-row').count(),22);
  await page.locator('#include-planned').uncheck();
  assert.equal(await page.locator('.log-row').count(),21);
  assert.equal(await page.locator('.planned-row').count(),0);
  await page.locator('#reset-filters').click();
  const mock=page.locator('.highlight-link[data-open-group="mock"]');
  await mock.click();
  assert.equal(await page.locator('#activity-dialog .dialog-event').count(),4);
  await page.keyboard.press('Escape');
  assert(await mock.evaluate(button=>document.activeElement===button),'Escape restores focus');
  await page.locator('#criteria-button').click();
  assert(await page.locator('#criteria-dialog').isVisible());
  await page.locator('#criteria-dialog [data-close-dialog]').click();
  await page.locator('[data-record-view="groups"]').click();
  assert.equal(await page.locator('.group-card').count(),12);
  await page.locator('.group-card[data-open-group="game-night"]').focus();
  await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.querySelector('.evidence-preview')?.complete&&document.querySelector('.evidence-preview')?.naturalWidth>0);
  assert(await page.locator('.evidence-preview').evaluate(image=>image.complete&&image.naturalWidth>0));
  assert.equal(await page.locator('#activity-dialog .event-status.connection').count(),1);
  await page.keyboard.press('Escape');
  await page.locator('#activity-search').fill('코멘토');
  const downloadEvent=page.waitForEvent('download');
  await page.locator('#download-records').click();
  const download=await downloadEvent;
  const csv=fs.readFileSync(await download.path(),'utf8');
  assert.equal(csv.trim().split('\r\n').length,7);
  assert(csv.includes('예정'));
  await page.goto(origin+'/career.html?month=2026-09');
  await page.locator('.career-nav a[href="#records"]').click();
  await page.locator('[data-category="competition"]').click();
  assert.equal(await page.locator('.log-row').count(),3);
  await page.goBack();
  assert.equal(await page.locator('.log-row').count(),8,'browser history restores filters');
  await page.goto(origin+'/career.html');
  await page.locator('.log-row[data-open-group="comento"]').first().click();
  await page.locator('[data-filter-group="comento"]').click();
  await page.waitForFunction(()=>document.activeElement.id==='records-title',null,{timeout:2000});
  assert.equal(await page.locator('.log-row').count(),6,'related records keep keyboard focus');
  await page.goto(origin+'/career.html?category=invalid&month=1999-01');
  assert.equal(await page.locator('.log-row').count(),22,'invalid filters fall back safely');
  for(const width of [320,390,800,1440])for(const theme of ['light','dark']){
   await page.setViewportSize({width,height:1000});
   await page.goto(origin+'/career.html');
   await page.evaluate(value=>window.portfolioTheme.setTheme(value),theme);
   const problems=await page.evaluate(()=>{
    const result=[];
    if(document.documentElement.scrollWidth>innerWidth+1)result.push('horizontal overflow');
    const ids=[...document.querySelectorAll('[id]')].map(element=>element.id);
    if(ids.length!==new Set(ids).size)result.push('duplicate IDs');
    for(const link of document.querySelectorAll('a[href^="#"]'))if(!document.getElementById(link.hash.slice(1)))result.push('missing anchor '+link.hash);
    const walker=document.createTreeWalker(document.querySelector('main'),NodeFilter.SHOW_TEXT);
    for(let node=walker.nextNode();node;node=walker.nextNode()){
     const value=node.textContent.trim();
     if(value.split(/\s+/).length>10)result.push('long copy: '+value);
    }
    return result;
   });
   if(problems.length)failures.push({width,theme,problems});
   if(output&&[390,1440].includes(width))await page.screenshot({path:path.join(output,`career-${width}-${theme}.png`),fullPage:true});
   await page.locator('[data-open-group="comento"]').first().click();
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
   assert(await page.locator('#activity-dialog').evaluate(dialog=>dialog.scrollWidth<=dialog.clientWidth+1));
   await page.keyboard.press('Escape');
  }
  const localLinks=await page.locator('a[href],link[href],script[src]').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('href')||node.getAttribute('src')).filter(href=>href&&!/^(https?:|#|mailto:)/.test(href)));
  for(const href of localLinks)assert(fs.existsSync(path.join(root,decodeURIComponent(href.split('#')[0]))),'local link exists: '+href);
  assert.deepEqual(errors,[]);assert.deepEqual(failures,[]);
  const report={journeys:'PASS',responsiveChecks:8,widths:[320,390,800,1440],themes:['light','dark'],copyWordLimit:10,errors,failures};
  if(output)fs.writeFileSync(path.join(output,'career-browser-results.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
 }finally{await browser.close();server.close();}
})().catch(error=>{console.error(error);process.exitCode=1});
